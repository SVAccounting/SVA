import assert from 'node:assert/strict';
import { scryptSync } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { kyivToday, activationScheduleError, verifySuperadminPassword } from '../netlify/functions/rulebook-activation-policy.js';

assert.equal(kyivToday(new Date('2026-11-22T21:30:00Z')), '2026-11-22');
assert.equal(kyivToday(new Date('2026-11-22T22:30:00Z')), '2026-11-23');
assert.equal(activationScheduleError('2026-11-22','2026-11-22',null,false),null,'Today is allowed with password');
assert.equal(activationScheduleError('2026-11-23','2026-11-22',null,false),null,'Tomorrow remains default');
assert.match(activationScheduleError('2026-11-21','2026-11-22',null,false),/заднім числом/);
assert.match(activationScheduleError('2026-11-23','2026-11-22','2026-11-24',false),/Запланована/);
assert.match(activationScheduleError('2026-11-22','2026-11-22','2026-11-24',true),/вже активоване/);
assert.equal(activationScheduleError('2026-11-22','2026-11-22','2026-11-24',false),null,'Same-day can coexist with future rule; UI warns it will be superseded');
const password='AnActualTestPasswordOnly!2026';
const salt='test-salt';
const user={salt,hash:scryptSync(password,salt,32).toString('hex')};
assert.equal(verifySuperadminPassword(password,user),true);
assert.equal(verifySuperadminPassword('wrong!',user),false);
assert.equal(verifySuperadminPassword('',user),false);
assert.equal(verifySuperadminPassword(password,{}),false);
const api=readFileSync(new URL('../netlify/functions/api.js',import.meta.url),'utf8');
assert.ok(api.includes("verifySuperadminPassword(password,auth)"),'API must verify the password server-side');
assert.ok(api.includes("WHERE id=${me.id} AND role='superadmin'"),'Verification must be for the authenticated superadmin');
assert.ok(api.indexOf('verifySuperadminPassword(password,auth)')<api.indexOf("const updated=(await sql`UPDATE accounting_rule_versions SET status='active'"),'Password check precedes publication');
const ui=readFileSync(new URL('../public/rulebook.js',import.meta.url),'utf8');
assert.ok(ui.includes('min="${TODAY()}"'),'Today must be selectable');
assert.ok(ui.includes('value="${h(when)}"'),'Selected date must survive re-render');
assert.ok(ui.includes('showTodayPassword(eff)'),'Same-day action must ask for password');
assert.ok(ui.includes('state.activationDate=dateTomorrow()'),'Default date must be tomorrow');
console.log('PASS: Kyiv dates, default tomorrow, exceptional today with password, server-side auth, history guards');
