import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';
import { DOC_TYPES, POSTING_KEYS,validatePosting,applyPosting,validateReport,evaluateReport } from '../netlify/functions/rule-engine.js';
import { REPORT_DEFAULTS } from '../netlify/functions/report-defaults.js';
import { REPORT_CODES } from '../netlify/functions/report-codes.js';
const project=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const file=p=>fs.readFileSync(path.join(project,p),'utf8');
const api=file('netlify/functions/api.js');
const ui=file('public/app2.js')+'\n'+file('public/app3.js');
assert.ok(DOC_TYPES.includes('prod') && POSTING_KEYS.includes('doc:prod'), 'finished goods must be mappable');
assert.match(api,/inventoryClaim/);assert.match(api,/inventory_revision/);
assert.match(api,/stock_moves\(company_id,doc_id,date,wh_id,item_id,qty,amount,lot_key\)/);
assert.match(api,/inventory_method:method,inventory_scope:scope/);
assert.match(api,/method==='spec'/);
assert.match(api,/stockable!=='no'/);
assert.match(api,/type==='prod'/);
assert.match(api,/mapEntries\('doc:'\+B\.type/);
assert.match(api,/posting_rule_version_id/);
assert.match(api,/scope='report' AND status='active'/);
assert.match(api,/if \(res === 'rulebook'\)/);
assert.match(ui,/Ціноутворення/);
assert.match(ui,/Випуск готової продукції/);
assert.match(file('public/index.html'),/rulebook\.js/);
assert.match(file('public/index.html'),/rulebook\/active\?at=/);
assert.match(file('public/forms.js'),/1420\|Нерозподілений прибуток \(непокритий збиток\)\|P:44/);
assert.equal(REPORT_DEFAULTS.F1P['1420'],'P:44');
// Mapping must leave accounting amount intact and never touch lot identifiers or physical quantity.
const original=[['902','281',120.34],['361','702',180]];
const config=validatePosting({mappings:[{from_debit:'361',from_credit:'702',to_debit:'361',to_credit:'701'}]});
const mapped=applyPosting(config,original);
assert.deepEqual(mapped,[['902','281',120.34],['361','701',180]]);
assert.deepEqual(original,[['902','281',120.34],['361','702',180]]);
const lot={lot_key:'f68ded0d-3a35-43e9-9300-c4037ca05a0c',qty:-4,amount:-120.34};
assert.equal(lot.lot_key,'f68ded0d-3a35-43e9-9300-c4037ca05a0c');
assert.equal(lot.qty,-4);
const stockResult=evaluateReport(REPORT_DEFAULTS.F1P,{},[{code:'44',closing:-700},{code:'791',closing:-300},{code:'702',closing:-800}],[]);
assert.equal(stockResult['1420'],700,'no duplicate unclosed 79 / income');
const custom=validateReport({rows:{'1420':'P:44;C:791'}},REPORT_CODES.F1P);
assert.equal(evaluateReport(REPORT_DEFAULTS.F1P,custom.rows,[{code:'44',closing:-700},{code:'791',closing:-300}],[])['1420'],1000);
// UI module mounts without browser dependency while leaving the inventory menu intact.
const panels={'#app':{innerHTML:''},'#rb_save':{disabled:false},'#rb_preview':{disabled:false},'#rb_activate':{disabled:false},'#rb_status':{textContent:''}};
const views={};const MENU=[['Склад',[['prod','Випуск готової продукції']]],['Ціноутворення',[['prices','Встановлення цін']]]];
const sandbox={views,MENU,F1A:[['1000','Тест','A:10']],F1P:[['1420','Прибуток','P:44']],F2:[['2000','Дохід','K:70']],me:{id:1,role:'superadmin'},company:{id:1,name:'Тест'},fmt:n=>String(n),esc:String,api:async()=>[],$:q=>panels[q]||({innerHTML:'',disabled:false}),window:null,console,Date,document:{querySelector:sel=>panels[sel]||null}};sandbox.window=sandbox;
vm.runInNewContext(file('public/rulebook.js'),sandbox,{filename:'rulebook.js'});
assert.ok(views.rulebook && views.ruleDiagnostics);
assert.equal(MENU.length,3);
assert.match(MENU[2][0],/Сервіс суперадміна/);
await views.rulebook();
assert.match(panels['#app'].innerHTML,/Конструктор бухгалтерської логіки/);
await views.ruleDiagnostics();
assert.match(panels['#app'].innerHTML,/Діагностика бухгалтерської логіки/);
console.log('PASS inventory compatibility, production document, rulebook server wiring, financial formula, menu mounting');
